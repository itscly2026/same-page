import assert from "node:assert/strict";
import { before, after, test } from "node:test";
import { chromium } from "playwright";
import { expect } from "@playwright/test";
import { startVisualServer } from "./setup.mjs";
import { resolveFixtureRequest } from "./fixtures.mjs";
let server;
before(async () => { server = await startVisualServer({ script: "dev" }); });
after(async () => { await server?.stop(); });
async function open(context, identity = "member", experience = false) {
  const browser = await chromium.launch({ headless: true });
  context.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1194, height: 700 }, hasTouch: true, serviceWorkers: "block" });
  await page.route("**/api/**", route => route.fulfill(resolveFixtureRequest({ pathname: new URL(route.request().url()).pathname, method: route.request().method(), identity: new URL(route.request().url()).searchParams.get("experience") === "1" ? "guest" : identity, scenarioId: "reader-controls-narrow", cookie: route.request().headers().cookie ?? "" })));
  await page.addInitScript(() => localStorage.setItem("reader-gesture-hint-seen", "true"));
  await page.goto(`${server.origin}/choirs/visual-choir/scores/visual-score${experience ? "?experience=1" : ""}`);
  await page.locator('.page-reader__sheet[data-page-turn-current] canvas[data-pdf-canvas-active]').waitFor();
  await page.locator('.page-reader__viewport').click({ position: { x: 590, y: 350 } });
  await page.getByRole('button', { name: '更多', exact: true }).click();
  return page;
}
test('landscape continuous fit contains the entire current page', async context => {
  const page = await open(context);
  await page.getByRole('button', { name: '连续滚动', exact: true }).click();
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '适合页面', exact: true }).click();
  await expect.poll(() => page.locator('.continuous-reader__page[data-index="0"] .annotated-pdf-page').evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(700);
});
