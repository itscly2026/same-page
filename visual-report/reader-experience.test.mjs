test('fitting the second continuous page keeps that page selected after rotation', async context => {
  const page = await open(context);
  await page.getByRole('button', { name: '连续滚动', exact: true }).click();
  await page.getByRole('slider', { name: '跳转页码' }).press('End');
  await expect(page.getByRole('slider', { name: '跳转页码' })).toHaveValue('2');
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '适合页面', exact: true }).click();
  const paper = page.locator('.continuous-reader__page[data-index="1"] .annotated-pdf-page');
  await expect.poll(() => paper.evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(700);
  await expect.poll(() => paper.evaluate(el => Math.abs(el.getBoundingClientRect().top))).toBeLessThan(2);
  await page.setViewportSize({ width: 700, height: 1194 });
  await expect.poll(() => paper.evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(1194);
  await expect(page.getByRole('slider', { name: '跳转页码' })).toHaveValue('2');
});
for (const layout of ['page', 'continuous']) test(`${layout}: two fingers cancel an ink checkpoint instead of saving an accidental stroke`, async context => {
  const page = await open(context, 'guest');
  if (layout === 'continuous') await page.getByRole('button', { name: '连续滚动', exact: true }).click();
  else await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByRole('button', { name: '画笔', exact: true }).click();
  const cdp = await page.context().newCDPSession(page);
  const send = (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points.map(([x, y, id]) => ({ x, y, id })) });
  await send('touchStart', [[500, 300, 1]]);
  await send('touchMove', [[520, 310, 1]]);
  await expect.poll(() => page.locator('[data-ink-draft]').count()).toBeGreaterThan(0);
  await expect.poll(() => page.evaluate(async () => {
    const { localDatabase } = await import('/src/client/platform/local-database.ts');
    return localDatabase.annotations.filter(note => note.payload?.kind === 'ink' && !note.deleted).count();
  })).toBeGreaterThan(0);
  await send('touchStart', [[520, 310, 1], [650, 310, 2]]);
  await send('touchMove', [[520, 290, 1], [650, 290, 2]]);
  await send('touchEnd', []);
  await page.getByRole('button', { name: '完成编辑', exact: true }).click();
  await page.reload();
  await page.locator(layout === 'page' ? '.page-reader__sheet[data-page-turn-current] canvas[data-pdf-canvas-active]' : '.continuous-reader__page[data-index="0"] canvas[data-pdf-canvas-active]').waitFor();
  assert.equal(await page.locator('[data-ink-stroke]').count(), 0);
});
