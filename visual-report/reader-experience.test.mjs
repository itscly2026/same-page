test('two-finger editing pans the score without leaving a text placement', async context => {
  const page = await open(context);
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: '放大', exact: true }).click();
  await page.getByRole('button', { name: '更多', exact: true }).click();
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.locator('.annotation-controls').waitFor();
  const reader = page.locator('.page-reader__viewport');
  await reader.evaluate(el => el.scrollTop = 150);
  const cdp = await page.context().newCDPSession(page);
  const send = (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points.map(([x, y, id]) => ({ x, y, id })) });
  await send('touchStart', [[500, 350, 1]]);
  await send('touchStart', [[500, 350, 1], [650, 350, 2]]);
  await send('touchMove', [[500, 300, 1], [650, 300, 2]]);
  await send('touchEnd', []);
  await expect.poll(() => reader.evaluate(el => el.scrollTop)).toBe(200);
  assert.equal(await page.getByRole('textbox', { name: '笔记文本' }).count(), 0);
  assert.equal(await page.locator('.page-reader__sheet[data-page-turn-current]').getAttribute('data-page-number'), '1');
});
